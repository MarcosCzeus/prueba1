-- PARTE 1: ejecutar como SYSTEM (en XEPDB1)
CREATE USER inventario IDENTIFIED BY "Inventario2026"
  DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;

GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO inventario;

-- PARTE 2: conectarse como INVENTARIO y ejecutar lo siguiente
CREATE TABLE producto (
  id      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo  VARCHAR2(30)  NOT NULL UNIQUE,
  nombre  VARCHAR2(120) NOT NULL,
  precio  NUMBER(12,2)  NOT NULL CHECK (precio >= 0),
  stock   NUMBER(10)    DEFAULT 0 NOT NULL CHECK (stock >= 0)
);

CREATE TABLE venta (
  id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  cliente      VARCHAR2(120) NOT NULL,
  producto_id  NUMBER(19)    NOT NULL REFERENCES producto (id),
  cantidad     NUMBER(10)    NOT NULL CHECK (cantidad > 0),
  precio       NUMBER(12,2)  NOT NULL,
  total        NUMBER(12,2)  NOT NULL
);

